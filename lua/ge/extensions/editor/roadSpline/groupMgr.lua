  paint.revert(group)

  if group.isLoop then
    -- Use the helper function for loop spline geometry splitting.
    group.nodes, group.widths, group.nmls = geom.splitLoopSplineGeometry(group.nodes, group.widths, group.nmls, selectedNodeIdx)
    group.isLoop = false
    group.isDirty = true
  else
    local nodes1, widths1, nmls1, nodes2, widths2, nmls2 = geom.splitSplineGeometry(group.nodes, group.widths, group.nmls, selectedNodeIdx)

    -- Prepare copies.
    local group1 = deepCopyGroup(group)
    group1.name = group.name .. " (1)"
    group1.id = Engine.generateUUID()
    group1.nodes = nodes1
    group1.widths = widths1
    group1.nmls = nmls1
    group1.isDirty = true

    local group2 = deepCopyGroup(group)
    group2.name = group.name .. " (2)"
    group2.id = Engine.generateUUID()
    group2.nodes = nodes2
    group2.widths = widths2
    group2.nmls = nmls2
